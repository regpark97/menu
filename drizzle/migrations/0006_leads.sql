-- Migration: tabela de leads captados pela landing page
-- Recebe os envios do formulário da LP (rota /) e alimenta a
-- aba "Leads" no painel Super Admin.

create table if not exists public.leads (
  id            bigint generated by default as identity primary key,
  establishment text not null,
  owner         text not null,
  phone         text not null,
  email         text not null,
  segment       text not null,
  status        text not null default 'new',  -- 'new' | 'contacted' | 'demo' | 'closed'
  created_at    timestamptz not null default now()
);

alter table public.leads enable row level security;

-- Insert público: o formulário da LP envia sem login (anon key).
create policy "public insert leads"
  on public.leads for insert
  to anon, authenticated
  with check (true);

-- Leitura e atualização: apenas Super Admin (mesmo padrão do resto do schema).
create policy "super admin read leads"
  on public.leads for select
  to authenticated
  using (public.has_role(auth.uid(), 'super_admin'));

create policy "super admin update leads"
  on public.leads for update
  to authenticated
  using (public.has_role(auth.uid(), 'super_admin'));

-- Índice para a listagem ordenada por data
create index if not exists leads_created_at_idx on public.leads (created_at desc);
